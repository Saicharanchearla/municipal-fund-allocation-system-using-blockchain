-- Public transparency data stored in Supabase PostgreSQL.
-- Edge Functions read with a server-side secret; the Data API grants no direct
-- access to anonymous or authenticated browser roles.
create table public.projects (
  id bigint generated by default as identity primary key,
  project_code text not null unique,
  project_name text not null,
  description text not null default '',
  category text not null default '',
  location text not null default '',
  ward_number text not null default '',
  government_department text not null default '',
  contractor_name text not null default '',
  contractor_gstin text not null default '',
  tender_reference text not null default '',
  work_order_number text not null default '',
  public_contact text not null default '',
  total_budget bigint not null check (total_budget >= 0),
  allocated_amount bigint not null default 0 check (allocated_amount >= 0),
  spent_amount bigint not null default 0 check (spent_amount >= 0),
  progress integer not null default 0 check (progress between 0 and 100),
  status text not null default 'PLANNING',
  start_date date,
  expected_end_date date,
  created_at timestamptz not null default now()
);

create table public.project_materials (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  material_name text not null,
  specification text not null default '',
  unit text not null default '',
  planned_quantity numeric(14,2) not null default 0,
  used_quantity numeric(14,2) not null default 0,
  unit_rate bigint not null default 0,
  vendor_name text not null default '',
  quality_status text not null default 'VERIFIED'
);
create index project_materials_project_id_idx on public.project_materials(project_id);

create table public.fund_transactions (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  transaction_code text not null unique,
  amount bigint not null check (amount >= 0),
  transaction_type text not null default 'EXPENDITURE',
  description text not null,
  vendor text not null default '',
  status text not null default 'APPROVED',
  occurred_at timestamptz not null default now(),
  blockchain_hash text not null,
  risk_level text not null default 'LOW',
  risk_score integer not null default 0 check (risk_score between 0 and 100)
);
create index fund_transactions_public_idx
  on public.fund_transactions(project_id, status, occurred_at desc);

create table public.citizen_feedback (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  citizen_name text,
  message text not null check (char_length(message) between 1 and 2000),
  category text not null default 'OTHER',
  status text not null default 'OPEN',
  created_at timestamptz not null default now()
);
create index citizen_feedback_project_created_idx
  on public.citizen_feedback(project_id, created_at desc);

alter table public.projects enable row level security;
alter table public.project_materials enable row level security;
alter table public.fund_transactions enable row level security;
alter table public.citizen_feedback enable row level security;
revoke all on public.projects, public.project_materials,
  public.fund_transactions, public.citizen_feedback
  from public, anon, authenticated;

